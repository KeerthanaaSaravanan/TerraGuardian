let currentLang: SupportedLanguage = "en";

export function setLanguage(lang: SupportedLanguage) {
  currentLang = lang;
  if (typeof window !== "undefined") {
    localStorage.setItem("tg_safe_lang", lang);
    window.dispatchEvent(new CustomEvent("tg_lang_changed", { detail: lang }));
  }
}

export function getLanguage(): SupportedLanguage {
  if (typeof window !== "undefined") {
    const saved = localStorage.getItem("tg_safe_lang") as SupportedLanguage;
    if (saved && TRANSLATIONS[saved]) return saved;
  }
  return currentLang;
}

export function t(key: string, langOverride?: SupportedLanguage): string {
  const lang = langOverride || getLanguage();
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}
